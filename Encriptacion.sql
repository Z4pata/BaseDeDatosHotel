USE master;
GO
-- Creacion llave maestra
CREATE MASTER KEY ENCRYPTION
BY PASSWORD='MiLlaveMaestra123*';
GO
-- Creacion certificado
CREATE CERTIFICATE TDE_HOTELERIACERT
WITH
SUBJECT='HOTELERIAMVP DATABASE ENCRYPTION';
GO

-- BackUp del certificado
BACKUP CERTIFICATE TDE_HOTELERIACERT
TO FILE='C:\SQLSERVERBackup\TDE_HOTELERIA_CERT'
WITH PRIVATE KEY (FILE='C:\SQLSERVERBackup\TDE_HOTELERIA_PrivateKey.pvk', 
ENCRYPTION BY PASSWORD='MiContraseñaDeEncriptacion123*')

-- Encriptamos la base de datos
USE Hotel;
GO

CREATE DATABASE ENCRYPTION KEY
WITH ALGORITHM = AES_256
ENCRYPTION BY SERVER CERTIFICATE TDE_HOTELERIACERT;

-- Verificamos el estado
SELECT NAME, IS_ENCRYPTED
FROM sys.databases
WHERE NAME = 'HOTEL';

-- Encender la encriptacion
ALTER DATABASE Hotel
SET ENCRYPTION ON;

-- BACKUP de la base de datos encriptada
BACKUP DATABASE [Hotel]
TO DISK ='C:\SQLSERVERBackup\Hotel_TDE.bak'
WITH NOFORMAT, INIT, NAME = 'Hotel con TDE',
SKIP, NOREWIND, NOUNLOAD, STATS = 10
GO